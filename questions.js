  function pickExactCount(blocks, targetCount) {
    for (let attempt = 0; attempt < 80; attempt++) {
      const shuffled = shuffleArr(blocks);
      const chosen = [];
      let sum = 0;
      for (const blk of shuffled) {
        if (sum + blk.length <= targetCount) {
          chosen.push(blk);
          sum += blk.length;
          if (sum === targetCount) return chosen;
        }
      }
    }
    // 備援精確回溯搜尋
    const shuffled = shuffleArr(blocks);
    function dfs(idx, curSum, acc) {
      if (curSum === targetCount) return acc;
      if (curSum > targetCount || idx >= shuffled.length) return null;
      const withCur = dfs(idx + 1, curSum + shuffled[idx].length, [...acc, shuffled[idx]]);
      if (withCur) return withCur;
      return dfs(idx + 1, curSum, acc);
    }
    return dfs(0, 0, []) || [];
  }

  let selectedBlocks = [];
  Object.keys(QUOTA).forEach(u => {
    selectedBlocks = selectedBlocks.concat(pickExactCount(blocksByUnit[u], QUOTA[u]));
  });

  // 隨機排列區塊順序並將每題選項洗牌（防背答案）
