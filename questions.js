function shuffleArr(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function shuffleQuestionOptions(q) {
  // 若題目有多選容錯 (如 112 Q9 ans=["A","C"]) 亦正確映射
  const keys = ["A", "B", "C", "D"];
  const perm = shuffleArr(keys);
  const newOptions = {};
  const newOptionImgs = q.optionImgs ? {} : null;
  const oldToNew = {};

  keys.forEach((newKey, idx) => {
    const oldKey = perm[idx];
    oldToNew[oldKey] = newKey;
    let txt = q.options[oldKey];
    // 若選項文字為「選項 (A)...」開頭，同步更新字母避免學生混淆
    txt = txt.replace(new RegExp(`選項\\s*\\(${oldKey}\\)`), `選項 (${newKey})`);
    newOptions[newKey] = txt;
    if (newOptionImgs) {
      newOptionImgs[newKey] = q.optionImgs[oldKey];
    }
  });

  const newAns = Array.isArray(q.ans)
    ? q.ans.map(a => oldToNew[a])
    : oldToNew[q.ans];

  return {
    ...q,
    options: newOptions,
    optionImgs: newOptionImgs || q.optionImgs,
    ans: newAns
  };
}

