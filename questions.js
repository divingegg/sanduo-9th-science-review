function toHalfWidth(str) {
  return String(str || "").replace(/[\uFF01-\uFF5E]/g, ch =>
    String.fromCharCode(ch.charCodeAt(0) - 0xFEE0)
  );
}

function normBasic(str) {
  return toHalfWidth(str).trim().replace(/\s+/g, "").toLowerCase();
}

function normNum(str, unitSuffixes = []) {
  let s = normBasic(str);
  for (const u of unitSuffixes) {
    if (s.endsWith(u.toLowerCase())) {
      s = s.slice(0, -u.length);
    }
  }
  if (s !== "" && !isNaN(Number(s))) {
    return String(Number(s));
  }
  return s;
}

